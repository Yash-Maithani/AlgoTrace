def preset_values(kind, n, seeds):
    script = ("const P=require('./algotrace/static/js/presets.js');"
              "console.log(JSON.stringify(%s.map(s=>P.generate('%s', %d, s))))"
              % (json.dumps(list(seeds)), kind, n))
    out = subprocess.run([NODE, '-e', script], capture_output=True, text=True, cwd=ROOT, check=True)
    return json.loads(out.stdout)


def both(t, values):
    a = sort_payload(t['left'], values, t['left_variant'])
    b = sort_payload(t['right'], values, t['right_variant'])
    return a, b


@pytest.mark.skipif(NODE is None, reason='node is not installed')
@pytest.mark.parametrize('index', range(len(COMPARE_TRIES)))
def test_what_to_try_claims_hold(index):
    t = COMPARE_TRIES[index]
    for values in preset_values(t['preset'], t['size'], range(1, 21)):
        a, b = both(t, values)
        ra, rb = a['result'], b['result']
        n = len(values)
        if index == 0:     # Merge finishes long before Bubble does
            assert len(b['steps']) * 2 < len(a['steps'])
        elif index == 1:   # n-1 for insertion, Quick's worst case
            assert ra['comparisons'] == n - 1
            assert rb['comparisons'] > 4 * ra['comparisons']
        elif index == 2:   # the middle pivot needs far fewer comparisons
            assert rb['comparisons'] * 2 < ra['comparisons']
        elif index == 3:   # only <= keeps the tags in order, with fewer comparisons
            assert ra['kept_equal_order'] is False and rb['kept_equal_order'] is True
            assert rb['comparisons'] < ra['comparisons']
        elif index == 4:   # same swaps, fewer comparisons with the early exit
            assert ra['swaps'] == rb['swaps']
            assert rb['comparisons'] < ra['comparisons']
        elif index == 5:   # none against over a hundred, and fewer steps
            assert ra['comparisons'] == 0
            assert rb['comparisons'] > 100
            assert len(a['steps']) < len(b['steps'])
        else:
            pytest.fail('try %d states a claim this test does not check' % index)


def test_every_try_names_real_algorithms_and_variants():
    from algotrace.catalog import sorting_algo_dict
    from algotrace.routes.sorting import SORT_VARIANTS
    ORDER = ['random', 'sorted', 'reversed', 'equal', 'nearly']   # Presets.ORDER
    assert "var ORDER = ['random', 'sorted', 'reversed', 'equal', 'nearly'];" in read('algotrace', 'static', 'js', 'presets.js')
    for t in COMPARE_TRIES:
        for side in ('left', 'right'):
            assert t[side] in sorting_algo_dict
            options = [o[0] for o in SORT_VARIANTS.get(t[side], {'options': []})['options']]
            assert (t[side + '_variant'] in options) if options else t[side + '_variant'] is None
        assert t['preset'] in ORDER
        assert 5 <= t['size'] <= 100
