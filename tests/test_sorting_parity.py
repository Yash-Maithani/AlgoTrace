@pytest.mark.parametrize('case,algo', PAIRS)
def test_result_matches_baseline(case, algo):
    """Sorted output, comparisons, swaps and step count are all unchanged."""
    payload = BASELINE['cases'][case]
    expected = payload['results'][algo]

    data, steps, stats = run(ALGORITHMS[algo], payload['input'])

    assert data == expected['sorted'], (
        '%s changed the sorted output for %s' % (algo, case))
    assert stats['comparisons'] == expected['comparisons'], (
        '%s changed its comparison count for %s' % (algo, case))
    assert stats['swaps'] == expected['swaps'], (
        '%s changed its swap count for %s' % (algo, case))
    assert len(steps) == expected['steps'], (
        '%s changed how many frames it draws for %s, which changes the '
        'animation' % (algo, case))


@pytest.mark.parametrize('case,algo', PAIRS)
def test_output_is_actually_sorted(case, algo):
    """The baseline is only worth freezing if it was correct to begin with."""
    payload = BASELINE['cases'][case]
    data, _, _ = run(ALGORITHMS[algo], payload['input'])

    assert data == sorted(payload['input'])


@pytest.mark.parametrize('case,algo', PAIRS)
def test_array_and_compared_are_unchanged(case, algo):
    """The two original fields still carry exactly what they used to.

    The teacher fields are additions. If one of them had replaced or reshaped
    `array` or `compared`, the stage would animate differently.
    """
    payload = BASELINE['cases'][case]
    _, steps, _ = run(ALGORITHMS[algo], payload['input'])

    for step in steps:
        assert isinstance(step['array'], list)
        assert len(step['array']) == len(payload['input'])
        assert isinstance(step['compared'], list)

    if steps:
        last = steps[-1]
        assert last['compared'] == ['green'] * len(payload['input'])
        assert last['array'] == sorted(payload['input'])


