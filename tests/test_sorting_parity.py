@pytest.mark.parametrize('case,algo', PAIRS)
def test_every_step_carries_the_teacher_fields(case, algo):
    """Shape check against static/js/lessons/README.md section 1."""
    payload = BASELINE['cases'][case]
    _, steps, _ = run(ALGORITHMS[algo], payload['input'])

    for position, step in enumerate(steps):
        where = '%s %s step %d' % (algo, case, position)

        for field in ('action', 'indices', 'values', 'line', 'vars', 'explain'):
            assert field in step, '%s is missing %s' % (where, field)

        assert step['action'] in ACTIONS, '%s has action %r' % (where, step['action'])
        assert isinstance(step['vars'], dict)
        assert step['line'] is None or isinstance(step['line'], str)

        assert len(step['indices']) == len(step['values']), (
            '%s has %d indices but %d values'
            % (where, len(step['indices']), len(step['values'])))
        assert all(isinstance(i, int) for i in step['indices']), (
            '%s put a non integer in indices' % where)
        assert all(0 <= i < len(step['array']) for i in step['indices']), (
            '%s points outside the array' % where)

        explain = step['explain']
        assert explain['beginner'].strip(), '%s has an empty explanation' % where
        assert explain['why'].strip(), '%s has an empty reason' % where


@pytest.mark.parametrize('case,algo', PAIRS)
def test_values_match_the_array_at_those_indices(case, algo):
    """`values` is a true reading of the array, not a hand written number."""
    payload = BASELINE['cases'][case]
    _, steps, _ = run(ALGORITHMS[algo], payload['input'])

    for position, step in enumerate(steps):
        for index, value in zip(step['indices'], step['values']):
            assert step['array'][index] == value, (
                '%s %s step %d says position %d holds %r, but the array it '
                'drew holds %r' % (algo, case, position, index, value,
                                   step['array'][index]))


@pytest.mark.parametrize('algo', sorted(ALGORITHMS))
def test_last_step_is_the_done_frame(algo):
    _, steps, _ = run(ALGORITHMS[algo], [5, 3, 8, 1, 9])

    assert steps[-1]['action'] == 'done'
    assert steps[-1]['line'] is None
    assert steps[-1]['indices'] == []


@pytest.mark.parametrize('algo', sorted(ALGORITHMS))
def test_explanations_name_the_real_values(algo):
    """An explanation has to talk about this input, not a generic example."""
    values = [42, 17, 93]
    _, steps, _ = run(ALGORITHMS[algo], values)

    first = steps[0]
    spoken = [v for v in first['values'] if str(v) in first['explain']['beginner']]
    assert spoken, (
        '%s opened with %r, which names none of the values it is acting on, %r'
        % (algo, first['explain']['beginner'], first['values']))


@pytest.mark.parametrize('algo', sorted(ALGORITHMS))
def test_line_ids_are_stable_for_a_known_input(algo):
    """Every id a step emits must exist in that algorithm's lesson listing.

    The lesson files are JavaScript, so this reads the ids out of them rather
    than importing them. It is a string check on purpose: it fails loudly if a
    `line` is renamed on one side only.
    """
    import re

    lesson_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        'static', 'js', 'lessons', '%s.js' % algo)
    with open(lesson_path, encoding='utf-8') as fh:
        lesson = fh.read()

    declared = set(re.findall(r"id:\s*'([^']+)'", lesson))

    _, steps, _ = run(ALGORITHMS[algo], [5, 3, 8, 1, 9, 2, 7])
    emitted = {s['line'] for s in steps if s['line'] is not None}

    missing = emitted - declared
    assert not missing, (
        '%s emits line ids that %s.js does not define: %s'
        % (algo, algo, sorted(missing)))


