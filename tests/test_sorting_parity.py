"""Phase 4 added teacher fields to every sorting step. Nothing else may move.

`tests/baseline_sorting.json` was generated by running the sorting package
exactly as it stood at commit e0fe171, the last commit before those fields
existed, over seventeen inputs covering random, sorted, reverse sorted,
duplicate and tiny arrays. These tests replay the same inputs against the
current code and demand the same answers.

What is frozen, per REBUILD_PLAN rules 1 and 2:
  the sorted output, the comparison count, the swap count, and the number
  of steps drawn, which is what rule 1 protects when it says the bars must
  animate as they did before.
"""
import json
import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sorting_algorithms.bubble_sort import bubble_sort
from sorting_algorithms.selection_sort import selection_sort
from sorting_algorithms.insertion_sort import insertion_sort
from sorting_algorithms.merge_sort import merge_sort
from sorting_algorithms.quick_sort import quick_sort
from sorting_algorithms.heap_sort import heap_sort

ALGORITHMS = {
    'bubble_sort': bubble_sort,
    'selection_sort': selection_sort,
    'insertion_sort': insertion_sort,
    'merge_sort': merge_sort,
    'quick_sort': quick_sort,
    'heap_sort': heap_sort,
}

ACTIONS = {'compare', 'swap', 'overwrite', 'select', 'place', 'done'}

BASELINE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                             'baseline_sorting.json')

with open(BASELINE_PATH, encoding='utf-8') as fh:
    BASELINE = json.load(fh)

CASES = sorted(BASELINE['cases'])
PAIRS = [(case, algo) for case in CASES for algo in sorted(ALGORITHMS)]


def run(algorithm, values):
    """Run a sort the way app.py does and collect its steps."""
    data = list(values)
    steps = []
    stats = {'swaps': 0, 'comparisons': 0}

    def draw(array_state, compared=None, meta=None):
        step = {
            'array': array_state[:],
            'compared': list(compared) if compared else [],
        }
        if meta:
            step.update(meta)
        steps.append(step)

    algorithm(data, draw, lambda: None, stats)
    return data, steps, stats


