def test_bubble_sort_has_no_early_exit():
    """The plan's headline divergence: best case here is quadratic, not O(n)."""
    sorted_input = [1, 2, 3, 4, 5, 6, 7, 8]
    _, _, stats = run(bubble_sort, sorted_input)

    n = len(sorted_input)
    assert stats['comparisons'] == n * (n - 1) // 2
    assert stats['swaps'] == 0


def test_selection_sort_comparison_count_ignores_the_input():
    n = 9
    counts = set()
    for values in ([1] * n, list(range(n)), list(range(n, 0, -1))):
        _, _, stats = run(selection_sort, values)
        counts.add(stats['comparisons'])

    assert counts == {n * (n - 1) // 2}


def test_insertion_sort_best_case_really_is_linear():
    """Unlike bubble sort, this one does break out of its inner loop."""
    values = list(range(1, 13))
    _, _, stats = run(insertion_sort, values)

    assert stats['comparisons'] == len(values) - 1
    assert stats['swaps'] == 0


def test_quick_sort_worst_case_is_sorted_input():
    """Last element pivot, so sorted input costs the full n(n-1)/2."""
    n = 10
    _, _, ordered = run(quick_sort, list(range(1, n + 1)))
    _, _, reversed_ = run(quick_sort, list(range(n, 0, -1)))

    assert ordered['comparisons'] == n * (n - 1) // 2
    assert reversed_['comparisons'] == n * (n - 1) // 2


def test_merge_sort_is_not_stable_in_this_implementation():
    """It compares with <, so equal values leave the right half first.

    The lesson file says so, and app.py reports stable: False for it. This
    test is what keeps those two honest if the comparison is ever changed.
    """
    class Tagged(int):
        def __new__(cls, value, tag):
            item = int.__new__(cls, value)
            item.tag = tag
            return item

    values = [Tagged(2, 'a'), Tagged(2, 'b'), Tagged(1, 'c')]
    data, _, _ = run(merge_sort, values)

    assert [int(v) for v in data] == [1, 2, 2]
    assert [v.tag for v in data] == ['c', 'b', 'a'], (
        'merge_sort became stable. Update merge_sort.js and the stable flag '
        'in app.py, which both record that it is not.')


@pytest.mark.parametrize('algo,values,comparisons,swaps,quoted_in', [
    # bubble_sort.js: "this input needs 4, a sorted list needs 0, and a
    # reversed one needs 10"
    ('bubble_sort', [5, 3, 8, 1, 9], 10, 4, 'worked.note'),
    ('bubble_sort', [1, 3, 5, 8, 9], 10, 0, 'worked.note'),
    ('bubble_sort', [9, 8, 5, 3, 1], 10, 10, 'worked.note'),
    # selection_sort.js: "2 here against bubble sort 4"
    ('selection_sort', [5, 3, 8, 1, 9], 10, 2, 'worked.note'),
    # insertion_sort.js: "sorted costs only 4 ... reversed costs the full 10"
    ('insertion_sort', [1, 3, 5, 8, 9], 4, 0, 'worked.note'),
    ('insertion_sort', [9, 8, 5, 3, 1], 10, 10, 'worked.note'),
    # merge_sort.js: "a run already in order uses fewer comparisons: 5"
    ('merge_sort', [1, 3, 5, 8, 9], 5, 12, 'worked.note'),
    # quick_sort.js: "feed it the sorted list and the count rises to 10"
    ('quick_sort', [1, 3, 5, 8, 9], 10, 14, 'worked.note'),
    # heap_sort.js: "the sorted list costs 12 here"
    ('heap_sort', [1, 3, 5, 8, 9], 12, 10, 'worked.note'),
])
def test_secondary_figures_quoted_in_lessons(algo, values, comparisons, swaps, quoted_in):
    """Every count a lesson prints in prose, not just the headline one."""
    _, _, stats = run(ALGORITHMS[algo], values)

    assert stats['comparisons'] == comparisons, (
        '%s.js %s quotes %d comparisons for %s, code makes %d'
        % (algo, quoted_in, comparisons, values, stats['comparisons']))
    assert stats['swaps'] == swaps, (
        '%s.js %s quotes %d swaps for %s, code makes %d'
        % (algo, quoted_in, swaps, values, stats['swaps']))
