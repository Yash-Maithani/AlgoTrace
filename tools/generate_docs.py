"""Builds AlgoTrace's reference documents from the site itself.

    python tools/generate_docs.py           write the files
    python tools/generate_docs.py --check   say whether they are current

They are in docs/project_documentation/. Project_Summary.md is written by hand;
this script writes the rest:

    Quick_Reference.md            the algorithms with their figures, the routes, the commands
    AlgoTrace_Documentation.txt   Project_Summary.md and Quick_Reference.md, as plain text
    AlgoTrace_Documentation.html  the same two documents as one page

The algorithm table is read from the lesson files (through tests/js/dump_lessons.js) and
the routes from the app itself, so the figures printed here are the ones the site shows and a
new algorithm appears without anyone typing it. Node is needed to regenerate; reading
the output needs nothing.
"""
import html
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs", "project_documentation")
sys.path.insert(0, ROOT)

FAMILIES = [("sorting", "Sorting"), ("searching", "Searching"), ("graph", "Graphs and grids")]
SYMBOLS = [(" squared", "²"), (" cubed", "³"), (" times ", "·"), (" plus ", " + "),
           ("square root of n", "√n")]


def figure(value):
    for old, new in SYMBOLS:
        value = value.replace(old, new)
    return value


def lessons():
    out = subprocess.run(["node", os.path.join(ROOT, "tests", "js", "dump_lessons.js")],
                         capture_output=True, text=True, encoding="utf-8", check=True).stdout
    data = json.loads(out)
    rows = []
    for key, entry in data.items():
        lesson = entry["resolved"][entry["default"] or ""]
        c = lesson["complexity"]
        rows.append({
            "id": key, "name": lesson["name"], "family": lesson["family"],
            "best": figure(c["time"]["best"]["value"]), "worst": figure(c["time"]["worst"]["value"]),
            "space": figure(c["space"]["value"]),
            "variants": sorted(entry["resolved"]) if lesson.get("variants") else [],
        })
    return rows


def routes():
    from wsgi import app
    pages, posts = [], []
    for rule in sorted(app.url_map.iter_rules(), key=lambda r: r.rule):
        if rule.endpoint == "static":
            continue
        if "POST" in rule.methods and "GET" not in rule.methods:
            posts.append(rule.rule)
        elif "GET" in rule.methods:
            pages.append(rule.rule)
    return pages, posts


def quick_reference():
    rows = lessons()
    pages, posts = routes()
    lines = ["# AlgoTrace: quick reference", "",
             "Generated by `tools/generate_docs.py` from the lesson files and the",
             "routes. Do not edit it by hand; edit the site or the script and run the script again.",
             "", "## The algorithms", "",
             "%d algorithms. Figures are the ones on each Complexity tab, derived from this code." % len(rows), ""]
    for family, title in FAMILIES:
        group = [r for r in rows if r["family"] == family]
        lines += ["### %s (%d)" % (title, len(group)), "",
                  "| Algorithm | Best | Worst | Extra memory | Variants |", "|---|---|---|---|---|"]
        for r in sorted(group, key=lambda r: r["name"]):
            lines.append("| %s | %s | %s | %s | %s |" % (
                r["name"], r["best"], r["worst"], r["space"], ", ".join(r["variants"]) or "none"))
        lines.append("")
    lines += ["## Pages", ""] + ["- `%s`" % p for p in pages] + [""]
    lines += ["## Endpoints that run an algorithm (POST, JSON)", ""] + ["- `%s`" % p for p in posts] + [""]
    lines += [
        "## Commands", "",
        "```", "pip install -r requirements.txt", "flask --app algotrace run --port 5002   # development, http://localhost:5002",
        "waitress-serve --host=127.0.0.1 --port=8000 wsgi:app   # production, Windows",
        "gunicorn wsgi:app --bind 127.0.0.1:8000                # production, Linux",
        "pip install -r requirements-dev.txt && python -m playwright install chromium",
        "pytest -q -m \"not slow\"              # about a minute", "pytest -q                          # everything, about 20 minutes, run alone",
        "python tools/check_banned_patterns.py .", "node tests/js/validate_lessons.js",
        "python tools/extract_code.py --check", "```", "",
        "## Environment variables", "",
        "| Variable | Use |", "|---|---|",
        "| `SITE_URL` | public address for canonical links, sitemap, robots and social previews |",
        "| `SECRET_KEY` | Flask secret key; nothing uses it today |",
        "| `FLASK_DEBUG` | `1` for debug mode on your own machine |",
        "| `TRUST_PROXY` | `1` behind one proxy, as on Render; the rate limit then counts the real client address |",
        "| `RATE_LIMIT_PER_MINUTE` | requests one address may make to `/run_*` a minute; 30 by default, 0 turns it off |",
        ""]
    return "\n".join(lines)


def read_summary():
    with open(os.path.join(DOCS, "Project_Summary.md"), encoding="utf-8") as fh:
        return fh.read()


def plain_text(markdown):
    out = []
    for line in markdown.splitlines():
        line = re.sub(r"^#{1,6}\s*", "", line)
        line = line.replace("**", "").replace("`", "")
        if re.fullmatch(r"\|[-| ]+\|", line.strip()):
            continue
        if line.startswith("|"):
            line = "  " + "  ".join(cell.strip() for cell in line.strip("|").split("|"))
        out.append(line)
    return "\n".join(out)


def to_html(markdown):
    body, in_code, in_list, in_table = [], False, False, False

    def close():
        nonlocal in_list, in_table
        if in_list:
            body.append("</ul>")
            in_list = False
        if in_table:
            body.append("</tbody></table>")
            in_table = False

    def inline(text):
        text = html.escape(text)
        text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
        return re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)

    for line in markdown.splitlines():
        if line.startswith("```"):
            close()
            body.append("</pre>" if in_code else "<pre>")
            in_code = not in_code
            continue
        if in_code:
            body.append(html.escape(line))
            continue
        heading = re.match(r"^(#{1,6})\s+(.*)", line)
        if heading:
            close()
            level = len(heading.group(1))
            body.append("<h%d>%s</h%d>" % (level, inline(heading.group(2)), level))
        elif line.startswith("|"):
            if re.fullmatch(r"\|[-| ]+\|", line.strip()):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if not in_table:
                close()
                body.append("<table><thead><tr>%s</tr></thead><tbody>" % "".join("<th>%s</th>" % inline(c) for c in cells))
                in_table = True
            else:
                body.append("<tr>%s</tr>" % "".join("<td>%s</td>" % inline(c) for c in cells))
        elif line.startswith("- "):
            if not in_list:
                close()
                body.append("<ul>")
                in_list = True
            body.append("<li>%s</li>" % inline(line[2:]))
        elif line.strip():
            close()
            body.append("<p>%s</p>" % inline(line))
        else:
            close()
    close()
    return "\n".join(body)


STYLE = """body { font-family: system-ui, sans-serif; line-height: 1.55; max-width: 960px; margin: 2rem auto; padding: 0 1rem; color: #1a1a18; }
table { border-collapse: collapse; margin: 1rem 0; } th, td { border: 1px solid #c9c5b8; padding: 4px 10px; text-align: left; }
code, pre { font-family: Consolas, monospace; background: #f1eee6; } pre { padding: 0.75rem; overflow-x: auto; }
h1 { border-bottom: 2px solid #1a1a18; } h2 { margin-top: 2rem; }"""


def documents():
    summary, reference = read_summary(), quick_reference()
    both = summary.rstrip() + "\n\n" + reference
    page = ("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"UTF-8\">\n"
            "<title>AlgoTrace: project documentation</title>\n<style>\n%s\n</style>\n</head>\n<body>\n%s\n</body>\n</html>\n"
            % (STYLE, to_html(both)))
    return {
        "Quick_Reference.md": reference,
        "AlgoTrace_Documentation.txt": plain_text(both) + "\n",
        "AlgoTrace_Documentation.html": page,
    }


def main(argv):
    docs = documents()
    stale = []
    for name, text in docs.items():
        path = os.path.join(DOCS, name)
        current = open(path, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(path) else None
        if current != text.replace("\r\n", "\n"):
            stale.append(name)
            if "--check" not in argv:
                with open(path, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(text.rstrip("\n") + "\n" if name.endswith(".md") else text)
    if "--check" in argv:
        print("out of date: %s" % ", ".join(stale) if stale else "ok: project documentation is current")
        return 1 if stale else 0
    print("wrote %s" % ", ".join(stale) if stale else "nothing to change")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
